def explain(errors: list[dict]) -> list[dict]:
    """Добавляет к ошибкам поле hint — что предложить пользователю."""
    out = []
    for e in errors or []:
        e = dict(e)
        hint = HINTS.get(e.get("code", ""))
        if hint:
            e["hint"] = hint
        out.append(e)
    return out
